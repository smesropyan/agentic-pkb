"""Deterministic generators for the derived files (invariant I3, rules GE-1 … GE-32).

Exactly three derived artifacts exist and this package is the only code that produces their content
(GE-1): the root ``index.md`` catalog, the root ``tags.md`` registry, and one ``index.md`` per topic
root. Everything else in the knowledge base is written by a human or an agent.

The contract every generator keeps, and why each half matters:

* **Wholesale replacement.** A derived file is truncated and replaced; its prior content is never
  read except to compare bytes (GE-2, GE-8). There is no version control (arch D6), so merging
  someone's hand edit into generated output would create a file nobody can reconstruct.
* **Never derived-as-input.** Tags rendered *inside* ``tags.md`` are output, not evidence of use
  (GE-3). Deleting every derived file and regenerating is the recovery mechanism, and it only works
  if the output does not depend on itself.
* **Byte-determinism.** No timestamp, no run id, no host, no version, no count (GE-6); every
  ordering has an explicit sort key (GE-4). The same tree renders the same bytes from any directory,
  under any hash seed, in any timezone — so a flush that changed nothing writes nothing (GE-5).
* **Total over a degraded tree.** A missing description renders a placeholder plus a diagnostic; a
  topic without a readable ``topic.md`` still gets its catalog line (GE-25). A file that is dropped
  from an index is invisible to every depth agent, which is a worse failure than an ugly line.

Rendering and writing are separate everywhere (GE-9): ``render_*`` is pure and takes a
:class:`~pkb.core.models.KbSnapshot`, ``generate_*`` renders and writes, and golden tests target the
pure half.
"""

